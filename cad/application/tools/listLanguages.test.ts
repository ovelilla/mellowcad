/**
 * LIST's report in each localized command language against its console
 * (review 32, LSK): the probe's answers typed in that language at LUPREC 4,
 * and the report's lines that carry each key a language words or pads its own
 * way, as the console wrote them. English and Spanish are held line for line
 * by list.test.ts.
 */

function listed(cad: CadHarness): string[] {
  return cad
    .commandLog()
    .filter((entry) => /^ {18}\S/.test(entry))
    .flatMap((entry) => entry.split("\n"))
}

function run(
  locale: Parameters<typeof createHarness>[0],
  answers: readonly string[]
): string[] {
  const cad = createHarness(locale)
  for (const text of ["_LUPREC", "4", ...answers]) {
    cad.runtime.setCommandLineText(text)
    cad.runtime.submitCommandLine()
  }
  return listed(cad)
}

